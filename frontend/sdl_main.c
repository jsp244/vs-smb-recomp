/* the Cabinet tab's switches: the game reads them when it starts, so the launcher's attract mode
   starts over with them; a game in progress gets them at its next reset */
static void apply_dips(void) {
    write_config();
    if (!game_started) {
        sys.vs_dip = attract_dips();
        if (rom_ok) { nes_power(); allstars_power(); rewind_clear(); chord_clear(); }
    } else {
        sys.vs_dip = dip_bits();
        snprintf(menu.status, sizeof menu.status, "The new switch settings take effect at the next reset (Play > Reset game)");
    }
}

static void menu_action(ui_event e) {
    if (e.type == UI_EV_BACK) {
        if (rom_ok && game_started) start_game();
        return;
    }
    if (e.type == UI_EV_CHANGED) {
        if (e.id == GFX_CHANGED) apply_graphics();
        else if (e.id == LAT_CHANGED) { audio_out_set_preset(cfg.audio_latency); write_config(); }
        else if (e.id == MUS_CHANGED) { apply_music(); write_config(); }
        else if (e.id == SLOT_CHANGED) select_slot(cfg.state_slot);
        else if (e.id == DIP_CHANGED) apply_dips();
        else write_config();
        return;
    }
    if (e.type != UI_EV_ACTIVATE) return;
    switch (e.id) {
    case ACT_PLAY: start_game(); break;
    case ACT_RESET: if (rom_ok) { sys.vs_dip = dip_bits(); nes_reset(); chord_clear(); game_started = 1; start_game(); } break;
    case ACT_SAVE: state_save(); break;
    case ACT_LOAD: if (state_load()) start_game(); break;
    case ACT_STOP:
        if (rom_ok) {
            battery_check(1);
            sys.vs_dip = attract_dips();
            nes_power(); allstars_power(); rewind_clear(); chord_clear(); game_started = 0;
            refresh_rom_items(); ui_select_first(&menu);
        }
        break;
    case ACT_QUIT: running = 0; break;
    case ACT_CHOOSE: choose_rom(); break;
    case ACT_CHOOSE_ALLSTARS: choose_allstars(); break;
    case ACT_KEYS_DEFAULT: {
        static const int def_keys[K_TOTAL] = { SDLK_x, SDLK_z, SDLK_RSHIFT, SDLK_RETURN, SDLK_UP, SDLK_DOWN, SDLK_LEFT, SDLK_RIGHT, SDLK_2,
                                               SDLK_BACKSPACE, SDLK_TAB };
        memcpy(cfg.key, def_keys, sizeof def_keys);
        input_default_pads(cfg.pad);
        cfg.pad[K_START2] = -1;
        cfg.pad[K_REWIND] = SDL_CONTROLLER_BUTTON_RIGHTSHOULDER;
        cfg.pad[K_FFWD] = INPUT_PAD_RT;
        write_config();
        break; }
    case ACT_UPDATE: {
        update_info u;
        updater_poll(&u);
        if ((u.state == UPD_AVAILABLE || u.state == UPD_CONFIRMING) && u.can_install) updater_install();
        else if (u.state == UPD_AVAILABLE) SDL_OpenURL(u.page);
        else if (u.state == UPD_INSTALLED && !FIXED_FULLSCREEN) { restart_after_quit = 1; running = 0; }
        else updater_check();      /* nothing happens while a check or a download runs */
        refresh_update_items();
        break; }
    default: break;
    }
}

