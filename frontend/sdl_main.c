static int file_mtime(const char *path, time_t *t) {
#ifdef _WIN32
    wchar_t w[2048];
    struct _stat st;
    if (!MultiByteToWideChar(CP_UTF8, 0, path, -1, w, 2048) || _wstat(w, &st) != 0) return 0;
#else
    struct stat st;
    if (stat(path, &st) != 0) return 0;
#endif
    *t = st.st_mtime;
    return 1;
}

static int move_file(const char *from, const char *to) {
#ifdef _WIN32
    wchar_t a[2048], b[2048];
    if (!MultiByteToWideChar(CP_UTF8, 0, from, -1, a, 2048) || !MultiByteToWideChar(CP_UTF8, 0, to, -1, b, 2048)) return -1;
    return _wrename(a, b);
#else
    return rename(from, to);
#endif
}

/* a message shown in the corner of the game for a couple of seconds (also printed) */
static void osd(const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(osd_text, sizeof osd_text, fmt, ap);
    va_end(ap);
    osd_until = SDL_GetTicks64() + 2200;
    printf("%s\n", osd_text);
}

#ifdef _WIN32
/* GUI-subsystem executable: reattach stdout/stderr when started from a console, unless the
   output is already redirected to a file or a pipe (keep that, so `> out.txt` works) */
static void attach_parent_console(void) {
    HANDLE h = GetStdHandle(STD_OUTPUT_HANDLE);
    if (h && h != INVALID_HANDLE_VALUE) {
        DWORD type = GetFileType(h);
        if (type == FILE_TYPE_DISK || type == FILE_TYPE_PIPE) return;
    }
    if (AttachConsole(ATTACH_PARENT_PROCESS)) {
        freopen("CONOUT$", "w", stdout);
        freopen("CONOUT$", "w", stderr);
    }
}
#endif

static char *trim(char *s) {
    while (isspace((unsigned char)*s)) s++;
    char *e = s + strlen(s);
    while (e > s && isspace((unsigned char)e[-1])) *--e = 0;
    return s;
}

/* absolute path for the remembered ROM, so a relative path given on the command line survives a double-click launch */
static void absolute_path(const char *in, char *out, size_t n) {
#ifdef _WIN32
    wchar_t win[4096], wfull[4096];
    if (MultiByteToWideChar(CP_UTF8, 0, in, -1, win, 4096) && GetFullPathNameW(win, 4096, wfull, NULL) &&
        WideCharToMultiByte(CP_UTF8, 0, wfull, -1, out, (int)n, NULL, NULL)) return;
#else
    char *r = realpath(in, NULL);
    if (r) { snprintf(out, n, "%s", r); free(r); return; }
#endif
    snprintf(out, n, "%s", in);
}

/* Settings and saves live next to the executable when that folder can be written
   (portable use). Otherwise (Program Files, a read-only share, running straight
   from inside a zip) they go to the per-user application-data folder, so the
   chosen ROM is remembered either way. */
static void choose_data_dir(void) {
    char probe[1200];
    snprintf(probe, sizeof probe, "%s.write-test", base_dir);
    FILE *f = nes_fopen(probe, "wb");
    if (f) {
        fclose(f);
#ifdef _WIN32
        wchar_t w[1200];
        if (MultiByteToWideChar(CP_UTF8, 0, probe, -1, w, 1200)) _wremove(w);
#else
        remove(probe);
#endif
        snprintf(data_dir, sizeof data_dir, "%s", base_dir);
        return;
    }
    char *p = SDL_GetPrefPath("VSSMBPort", "VSSuperMarioBros");
    if (p) { snprintf(data_dir, sizeof data_dir, "%s", p); SDL_free(p); }
    else snprintf(data_dir, sizeof data_dir, "%s", base_dir);
}

