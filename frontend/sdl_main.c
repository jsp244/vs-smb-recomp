    if (cfg.resolution > 0 && cfg.resolution < n_res) { cfg.res_w = res_list[cfg.resolution].w; cfg.res_h = res_list[cfg.resolution].h; }
    else { cfg.resolution = 0; cfg.res_w = cfg.res_h = 0; }
