static uint64_t fb_hash(void) {
    uint64_t h = 0xcbf29ce484222325ULL;
    for (size_t i = 0; i < sizeof ppu.fb; i++) { h ^= ppu.fb[i]; h *= 0x100000001b3ULL; }
    return h;
}

/* --rewind-test N: run N frames recording the picture of each and the rewind history every
   other frame, then step back through the whole history checking that every re-run frame
   matches what was recorded on the way forward */
static int rewind_selftest(int frames) {
    frames &= ~1;
    size_t sz = nes_state_size();
    void *st = malloc(sz);
    uint64_t *hashes = malloc(sizeof(uint64_t) * (size_t)(frames + 1));
    if (!rewind_init(sz, 8u << 20)) { printf("rewind-test: init failed\n"); return 1; }
    #define TEST_PAD(f) ((uint8_t)(((f) >= 150 && (f) < 160) || ((f) >= 400 && (f) < 410) ? 0x08 : ((f) >= 600 && (f) < 700) ? 0x80 : 0))
    for (int f = 1; f <= frames; f++) {
        nes_set_pad(0, TEST_PAD(f));
        nes_run_frame();
        hashes[f] = fb_hash();
        if ((f & 1) == 0) { nes_state_save(st, sz); rewind_push(st); }
    }
    size_t used = rewind_bytes_used();
    void *final_state = malloc(sz);
    nes_state_save(final_state, sz);
    int steps = 0, ok = 1;
    for (int f = frames; f >= 4; f -= 2) {
        if (!rewind_pop(st)) { printf("rewind-test: history ended early at frame %d\n", f); ok = 0; break; }
        nes_state_load(st, sz);
        allstars_reset();
        apu_flush_samples();
        nes_set_pad(0, TEST_PAD(f - 1));
        nes_run_frame();
        if (fb_hash() != hashes[f - 1]) { printf("rewind-test: frame %d differs after rewinding\n", f - 1); ok = 0; break; }
        steps++;
    }
    /* the player goes on for a second right after the rewind: inside the undo window nothing
       is recorded, so fast-forward can still go forward through the whole rewound stretch */
    if (ok) {
        void *live = malloc(sz);
        redo_hold = REDO_WINDOW;
        int pushed = 0;
        for (int i = 1; i <= 60; i++) { nes_set_pad(0, 0x80); nes_run_frame(); pushed += history_step(i, live, sz); }
        free(live);
        if (pushed) { printf("rewind-test: %d records made inside the undo window\n", pushed); ok = 0; }
    }
    /* forward again (fast-forward after a rewind): every redone state must give the frames of the first run,
       and the last one must be the state the rewind started from */
    int fwd = 0;
    if (ok) {
        if (rewind_redo_count() != steps) { printf("rewind-test: %d steps can be undone, expected %d\n", rewind_redo_count(), steps); ok = 0; }
        for (int f = 4; ok && f <= frames; f += 2) {
            if (!rewind_redo(st)) { printf("rewind-test: forward history ended early at frame %d\n", f); ok = 0; break; }
            if (f == frames) { if (memcmp(st, final_state, sz) != 0) { printf("rewind-test: forward did not return to the newest state\n"); ok = 0; } }
            else {
                nes_state_load(st, sz);
                allstars_reset();
                apu_flush_samples();
                nes_set_pad(0, TEST_PAD(f + 1));
                nes_run_frame();
                if (fb_hash() != hashes[f + 1]) { printf("rewind-test: frame %d differs going forward again\n", f + 1); ok = 0; break; }
            }
            fwd++;
        }
        if (ok && (rewind_redo(st) || rewind_redo_count() != 0)) { printf("rewind-test: forward went past the newest state\n"); ok = 0; }
    }
    /* two steps back, then playing on past the window: the history records again and the stretch is gone */
    if (ok) {
        rewind_pop(st); rewind_pop(st);
        nes_state_load(st, sz);
        allstars_reset();
        redo_hold = REDO_WINDOW;
        int first = 0;
        for (int i = 1; i <= REDO_WINDOW + 4 && !first; i++) { nes_run_frame(); if (history_step(i, st, sz)) first = i; }
        if (first < REDO_WINDOW || rewind_redo_count() != 0) { printf("rewind-test: the undo window ended at frame %d, expected %d\n", first, REDO_WINDOW); ok = 0; }
    }
    #undef TEST_PAD
    printf("rewind-test: %d frames forward, %d steps back, %d steps forward again: %s; history %zu bytes (%.0f bytes per record)\n",
           frames, steps, fwd, ok ? "all matched" : "FAILED", used, (double)used / (frames / 2));
    rewind_shutdown();
    free(st); free(hashes); free(final_state);
    return ok ? 0 : 1;
}

/* --reset-test N: N frames of the attract mode, then Play > Reset game through the menu's own action,
   timed. The reset must take far less than a frame however long the game ran (it used to run every PPU
   dot since power-on again: ~0.17 ms per frame played, over half a minute after an hour), keep the PPU's
   frame count (the remastered graphics count frames across it) and its clock at the CPU's x 3, and start
   the game over: the CPU at the reset vector, the picture off and soon on again, the game's frame counter
   ($09) set up again from 0 and then counting every frame */
static int reset_selftest(int frames) {
    int failures = 0, back_on = 0, counting = 0;
    char msg[200];
#define CHECK(cond, text) do { int c_ = (cond); printf("%s %s\n", c_ ? "ok:  " : "FAIL:", text); if (!c_) failures++; } while (0)
    for (int i = 0; i < frames; i++) nes_run_frame();
    apu_flush_samples();
    uint64_t frame0 = ppu.frame;
    uint8_t counter0 = ram[0x09], counter30 = 0;
    uint64_t t0 = SDL_GetPerformanceCounter();
    menu_action((ui_event){ UI_EV_ACTIVATE, ACT_RESET });
    double ms = (double)(SDL_GetPerformanceCounter() - t0) * 1000.0 / (double)SDL_GetPerformanceFrequency();
    snprintf(msg, sizeof msg, "Play > Reset game after %d frames took %.3f ms (less than a frame)", frames, ms);
    CHECK(ms < 16.0, msg);
    CHECK(ppu.frame == frame0, "the PPU's frame count goes on (not counted again from power-on)");
    CHECK(ppu.dots == cpu.cycles * 3, "the PPU's clock is still the CPU's x 3");
    CHECK(state == ST_GAME && cpu.pc == mem_read16(0xFFFC) && (ppu.mask & 0x18) == 0,
          "the game runs from the reset vector, with the PPU's registers reset (picture off)");
    for (int i = 1; i <= 600; i++) {
        uint8_t prev = ram[0x09];
        nes_run_frame();
        apu_flush_samples();
        if (!back_on && (ppu.mask & 0x18)) back_on = i;
        if (i == 30) counter30 = ram[0x09];
        if (i > 500) counting += ram[0x09] == (uint8_t)(prev + 1);
    }
    CHECK(ppu.frame == frame0 + 600, "after it, one PPU frame per frame run");
    snprintf(msg, sizeof msg, "the game started over: the picture on again %d frames after the reset, its frame counter at %d "
             "30 frames after it (%d without the reset), then counting every frame", back_on, counter30, (uint8_t)(counter0 + 30));
    CHECK(back_on > 0 && back_on < 60 && counter30 < 30 && counter30 != (uint8_t)(counter0 + 30) && counting == 100, msg);
#undef CHECK
    printf("reset-test: %s (%d failure%s)\n", failures ? "FAILED" : "all passed", failures, failures == 1 ? "" : "s");
    return failures ? 1 : 0;
}

