/* the picture region uv of tex (tw x th texels) drawn into pic with barrel curvature:
   the corners are pulled in, the middles of the edges stay, like the face of a tube */
static void draw_curved(SDL_Texture *tex, int tw, int th, const SDL_Rect *uv, const SDL_Rect *pic) {
    enum { NX = 32, NY = 24, NV = (NX + 1) * (NY + 1), NI = NX * NY * 6 };
    static SDL_Vertex v[NV];
    static int idx[NI];
    static int idx_ready;
    const double k = 0.045 * fx_strength();
    const SDL_Color white = { 255, 255, 255, 255 };
    for (int j = 0; j <= NY; j++) for (int i = 0; i <= NX; i++) {
        double u = (double)i / NX, w = (double)j / NY;
        double x = u * 2 - 1, y = w * 2 - 1;
        double f = (1 + k) / (1 + k * (x * x + y * y));
        SDL_Vertex *p = &v[j * (NX + 1) + i];
        p->position.x = (float)(pic->x + pic->w * 0.5 + x * f * pic->w * 0.5);
        p->position.y = (float)(pic->y + pic->h * 0.5 + y * f * pic->h * 0.5);
        p->color = white;
        p->tex_coord.x = (float)((uv->x + u * uv->w) / tw);
        p->tex_coord.y = (float)((uv->y + w * uv->h) / th);
    }
    if (!idx_ready) {
        int n = 0;
        for (int j = 0; j < NY; j++) for (int i = 0; i < NX; i++) {
            int a = j * (NX + 1) + i, b = a + 1, c = a + NX + 1, d = c + 1;
            idx[n++] = a; idx[n++] = b; idx[n++] = c;
            idx[n++] = b; idx[n++] = d; idx[n++] = c;
        }
        idx_ready = 1;
    }
    SDL_RenderGeometry(renderer, tex, v, NV, idx, NI);
}

/* draw the current game frame into the window (no present).
   backdrop = 1 renders it as the launcher hero: aspect-correct, filling the
   window, with the sharp filter and no effects regardless of the user's settings. */
static void draw_game_ex(int backdrop) {
    int ww, wh;
    SDL_GetRendererOutputSize(renderer, &ww, &wh);
    SDL_Rect src, dst;
    int saved_scaling = cfg.scaling, saved_filter = cfg.filter;
    /* where the picture is composed: the window, or in fullscreen the chosen
       resolution, scaled to the screen afterwards */
    int out_w = ww, out_h = wh;
    int internal = !backdrop && cfg.display_mode == 1 && cfg.res_w > 0;
    if (internal) { out_w = cfg.res_w; out_h = cfg.res_h; }
    pic_out_w = backdrop ? 0 : out_w;   /* the menu's backdrop keeps the chosen shape */
    pic_out_h = out_h;
    source_rect(&src);
    int fx = !backdrop && cfg.shader != 0;
    int use_scene = fx || internal;
    if (backdrop) {
        /* cover the window: scale so the shorter side fills, centre the rest */
        double aspect = target_aspect(src.h);
        int w = ww, h = (int)(w / aspect + 0.5);
        if (h < wh) { h = wh; w = (int)(h * aspect + 0.5); }
        dst.x = (ww - w) / 2; dst.y = (wh - h) / 2; dst.w = w; dst.h = h;
        cfg.filter = 2;
    } else {
        dest_rect(out_w, out_h, &src, &dst);
    }
    /* the part of the picture on the output (Integer filling the screen lets it overhang the edges):
       the curvature mesh, the vignette and the mask follow it */
    SDL_Rect vis, out_rect = { 0, 0, out_w, out_h };
    if (!SDL_IntersectRect(&dst, &out_rect, &vis)) vis = dst;
    int k = (dst.h + src.h - 1) / src.h;
    if (k < 1) k = 1;
    if (k > 8) k = 8;
    frame_to_rgb(&src);
    ensure_textures(k);
    SDL_UpdateTexture(game_tex, NULL, frame_rgb, frame_w * (int)sizeof(uint32_t));
    if (use_scene) {
        ensure_scene_tex(out_w, out_h);
        if (scene_tex) SDL_SetRenderTarget(renderer, scene_tex);
        else use_scene = 0;
    }
    SDL_Texture *target = use_scene ? scene_tex : NULL;
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderClear(renderer);
    if (cfg.filter == 2 && sharp_tex) {
        SDL_SetRenderTarget(renderer, sharp_tex);
        SDL_RenderCopy(renderer, game_tex, NULL, NULL);
        SDL_SetRenderTarget(renderer, target);
        SDL_RenderCopy(renderer, sharp_tex, NULL, &dst);
    } else {
        SDL_RenderCopy(renderer, game_tex, NULL, &dst);
    }
    if (fx) {
        if (fx_glow()) {
            ensure_glow_tex((src.w + 2) / 3, (src.h + 2) / 3);
            if (glow_tex) {
                SDL_SetRenderTarget(renderer, glow_tex);
                SDL_SetTextureScaleMode(game_tex, SDL_ScaleModeLinear);
                SDL_RenderCopy(renderer, game_tex, NULL, NULL);
                SDL_SetTextureScaleMode(game_tex, cfg.filter == 1 ? SDL_ScaleModeLinear : SDL_ScaleModeNearest);
                SDL_SetRenderTarget(renderer, target);
                double g = 0.30 * fx_strength();
                if (g > 0.6) g = 0.6;
                SDL_SetTextureAlphaMod(glow_tex, (Uint8)(255 * g + 0.5));
                SDL_RenderCopy(renderer, glow_tex, NULL, &dst);
            }
        }
        if (fx_scan()) { ensure_scan_tex(src.h); if (scan_tex) SDL_RenderCopy(renderer, scan_tex, NULL, &dst); }
        if (fx_curve()) { ensure_vig_tex(); if (vig_tex) SDL_RenderCopy(renderer, vig_tex, NULL, &vis); }
    }
    if (use_scene) {
        SDL_SetRenderTarget(renderer, NULL);
        SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
        SDL_RenderClear(renderer);
        /* the composed picture on the screen: 1:1, or scaled to fit when it was rendered at another size */
        SDL_Rect screen = { 0, 0, ww, wh };
        if (internal) {
            int w = ww, h = (int)((double)w * out_h / out_w + 0.5);
            if (h > wh) { h = wh; w = (int)((double)h * out_w / out_h + 0.5); }
            screen = (SDL_Rect){ (ww - w) / 2, (wh - h) / 2, w, h };
        }
        SDL_Rect pic = { screen.x + (int)((double)vis.x * screen.w / out_w + 0.5), screen.y + (int)((double)vis.y * screen.h / out_h + 0.5),
                         (int)((double)vis.w * screen.w / out_w + 0.5), (int)((double)vis.h * screen.h / out_h + 0.5) };
        if (fx && fx_curve()) draw_curved(scene_tex, out_w, out_h, &vis, &pic);
        else SDL_RenderCopy(renderer, scene_tex, NULL, &screen);
        if (fx && fx_mask()) { ensure_mask_tex(pic.w); if (mask_tex) SDL_RenderCopy(renderer, mask_tex, NULL, &pic); }
    }
    cfg.scaling = saved_scaling;
    cfg.filter = saved_filter;
}

