/* the 16:9 and 16:10 aspect choices are the widescreen modes: the level drawn beside the picture
   during play, the normal 4:3 picture between black bars elsewhere, never a stretch */
static int widescreen_on(void) { return cfg.aspect >= 2; }

static double target_aspect(int src_h) {
    switch (cfg.aspect) {
    case 1: return 4.0 / 3.0;
    case 2: return 16.0 / 9.0;
    case 3: return 16.0 / 10.0;
    default: return (double)FB_W / src_h;
    }
}

/* width of a pixel relative to its height: square, or the 4:3 CRT look, which the
   16:9 mode keeps (it adds picture at the sides instead of changing the pixel shape) */
static double pixel_aspect(void) { return cfg.aspect == 0 ? 1.0 : 1.25; }

/* the output the picture is composed for, set by its users before source_rect */
static int pic_out_w, pic_out_h;

/* Integer scaling with a widescreen aspect on a fixed screen (fullscreen, a handheld) fills the
   whole width: the picture at the largest whole multiple that fits it, with the level beyond its
   edges wherever the game holds it (other screens keep the normal picture between black bars).
   Returns the multiple, 0 when the picture is not filled. */
static int integer_fill(void) {
    if (cfg.scaling != 0 || !widescreen_on() || cfg.display_mode == 0 || pic_out_w <= 0) return 0;
    int k = pic_out_h / (cfg.overscan ? FB_H - 2 * OVERSCAN : FB_H);
    while (k > 1 && FB_W * k * pixel_aspect() > pic_out_w + 0.5) k--;
    return k < 1 ? 1 : k;
}

/* the lines and columns added on each side of the normal picture to cover the output at k */
static void fill_extent(int k, int *ext_y, int *ext_x) {
    int base = cfg.overscan ? FB_H - 2 * OVERSCAN : FB_H, ov = cfg.overscan ? OVERSCAN : 0;
    int bars = pic_out_h - base * k, bar = bars - bars / 2;   /* the larger of the two bars */
    *ext_y = bar > 0 ? (bar + k - 1) / k : 0;
    if (*ext_y > WS_VBAND + ov) *ext_y = WS_VBAND + ov;
    double px = k * pixel_aspect(), bar_x = (pic_out_w - FB_W * px) / 2;
    *ext_x = bar_x > 0 ? (int)ceil(bar_x / px - 1e-6) : 0;
    if (*ext_x > WS_BAND) *ext_x = WS_BAND;
}

/* The part of the frame shown: of the PPU's picture, or in widescreen mode of the canvas around it
   (widescreen.h): the part that makes a 16:9 or 16:10 picture at the pixel aspect, or with Integer
   filling the screen every line and column the output holds at the multiple. */
static void source_rect(SDL_Rect *src) {
    int k = integer_fill();
    src->y = cfg.overscan ? OVERSCAN : 0;
    src->h = cfg.overscan ? FB_H - 2 * OVERSCAN : FB_H;
    if (k) {
        int ey, ex;
        fill_extent(k, &ey, &ex);
        src->x = WS_BAND - ex; src->w = FB_W + 2 * ex;
        src->y += WS_VBAND - ey; src->h += 2 * ey;
    } else if (widescreen_on()) {
        src->w = widescreen_visible_width(src->h, pixel_aspect(), target_aspect(src->h));
        src->x = (WS_W - src->w) / 2;
        src->y += WS_VBAND;
    } else {
        src->x = 0; src->w = FB_W;
    }
}

/* how far left of the screen the player may walk (bandwalk.c): as far as the game's picture shows
   the band there, in whole columns where Integer filling the screen cuts the outermost one */
static int walk_band(void) {
    if (!cfg.walk_to_edge || !widescreen_on() || !renderer) return 0;
    int ww, wh;
    SDL_GetRendererOutputSize(renderer, &ww, &wh);
    if (cfg.display_mode == 1 && cfg.res_w > 0) { ww = cfg.res_w; wh = cfg.res_h; }
    pic_out_w = ww;   /* the game's picture, not the menu's backdrop */
    pic_out_h = wh;
    int k = integer_fill();
    if (k) {
        double px = k * pixel_aspect(), bar = (pic_out_w - FB_W * px) / 2;
        int b = bar > 0 ? (int)(bar / px + 1e-6) : 0;
        return b > WS_BAND ? WS_BAND : b;
    }
    SDL_Rect src;
    source_rect(&src);
    return WS_BAND - src.x;
}

static void dest_rect(int ww, int wh, const SDL_Rect *src, SDL_Rect *dst) {
    double aspect = target_aspect(src->h);
    int w, h, k = integer_fill();
    if (k) {
        /* the normal picture where Integer puts it, the added lines and columns around it; the
           outermost pixels may lie partly beyond the edges */
        int ey, ex, base = cfg.overscan ? FB_H - 2 * OVERSCAN : FB_H;
        fill_extent(k, &ey, &ex);
        double px = k * pixel_aspect();
        dst->y = (wh - base * k) / 2 - ey * k; dst->h = src->h * k;
        dst->x = (int)floor((ww - FB_W * px) / 2 - ex * px + 0.5); dst->w = (int)floor(src->w * px + 0.5);
        return;
    }
    if (cfg.scaling == 2) { dst->x = 0; dst->y = 0; dst->w = ww; dst->h = wh; return; }
    if (cfg.scaling == 0) {
        k = wh / src->h;
        if (k < 1) k = 1;
        while (k > 1 && (int)(src->h * k * aspect + 0.5) > ww) k--;
        h = src->h * k;
        w = (int)(h * aspect + 0.5);
    } else {
        w = ww; h = (int)(w / aspect + 0.5);
        if (h > wh) { h = wh; w = (int)(h * aspect + 0.5); }
    }
    dst->x = (ww - w) / 2; dst->y = (wh - h) / 2; dst->w = w; dst->h = h;
}

/* the colours: the arcade monitor's (the RP2C04-0004's own RGB palette), or the ones the NES
   version shows (each colour through the PPU's table to the 2C02's composite colour) */
static void build_palette(void) {
    if (!cart.vs) nes_palette_build(palette);
    else if (cfg.colors == 1) nes_palette_build_vs_composite(palette, cart.vs_ppu);
    else nes_palette_build_rgb(palette, cart.vs_ppu);
}

/* the Cabinet tab as the board's DIP switches (bit k = switch k+1 on). The game reads switches 1-3
   as a coinage number 4 * sw1 + 2 * sw2 + sw3 (0-6 = 1c/1c, 2c/1c, 3c/1c, 1c/2c, 1c/3c, 1c/4c,
   1c/5c, 7 = free play), switch 4 = two lives instead of three, 5-6 as 2 * sw5 + sw6 = 100 / 150 /
   200 / 250 coins for an extra life, 7 = fast timer, 8 = three lives after a continue, not four */
static uint8_t dip_bits(void) {
    int c = cfg.coinage == 0 ? 7 : cfg.coinage - 1;
    uint8_t d = (uint8_t)(((c >> 2) & 1) | ((c >> 1) & 1) << 1 | (c & 1) << 2);
    if (cfg.lives) d |= 0x08;
    if (cfg.bonus & 2) d |= 0x10;
    if (cfg.bonus & 1) d |= 0x20;
    if (cfg.fast_timer) d |= 0x40;
    if (cfg.continue_lives) d |= 0x80;
    return d;
}

/* The launcher shows the title and the demo, which the board only plays while it has no credits:
   with free play set, the attract mode behind the menu runs as on a coin-op, and a game starts
   with the real switches (start_game). */
static uint8_t attract_dips(void) {
    uint8_t d = dip_bits();
    return (d & 7) == 7 ? (uint8_t)(d & ~7) : d;
}

