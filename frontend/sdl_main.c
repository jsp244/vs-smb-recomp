/* ------------------------------------------------------------------ */
/* Start + Select: the menu from the pad                               */
/* ------------------------------------------------------------------ */
/* Pressing Start and Select (Insert coin) together opens the menu. The two rarely go down on the
   same frame, and the game reacts to the first one alone (a coin drops, a game starts), so the
   frontend keeps the machine state from before each of the last few frames: when the chord
   completes it goes back to before the first of the two was pressed. The game never sees half a
   chord and no input is delayed. */
#define CHORD_BITS  0x0C         /* Select (bit 2) | Start (bit 3) */
#define ACTION_BITS 0x0F         /* A, B, Select, Start */
#define CHORD_RING  10           /* frames kept: the second button may follow within 9 frames (150 ms) */
static uint8_t *chord_states;    /* CHORD_RING machine states, each from before a real frame */
static size_t chord_size;
static uint8_t chord_pads[CHORD_RING];     /* the pad that frame ran with */
static uint8_t chord_pushed[CHORD_RING];   /* a rewind record was pushed after that frame */
static int chord_head, chord_count;
static uint8_t prev_game_pad;    /* the last pad given to the game, for press edges */
static uint8_t suppress_mask;    /* buttons held when the game resumed: hidden from it until released */
static int pad_override = -1;    /* tests: the pad to use instead of the keyboard and controllers */

/* the timeline was replaced (state load, rewind, reset, power): the kept states are stale */
static void chord_clear(void) { chord_count = 0; }

static uint8_t raw_pad(void) {
    return pad_override >= 0 ? (uint8_t)pad_override : (uint8_t)(input_read(cfg.key, cfg.pad) | touchpad_buttons());
}

/* the NES pad as the game should see it */
static uint8_t game_pad(void) {
    uint8_t raw = raw_pad();
    suppress_mask &= raw;                                              /* released buttons are seen again */
    if (suppress_mask & CHORD_BITS) suppress_mask |= raw & CHORD_BITS;  /* the other half of a closing chord */
    return (uint8_t)(raw & ~suppress_mask);
}

/* leaving the menu: buttons still held (Start to resume, A to confirm) are not passed to the
   game until they are released; the d-pad is (a held direction just keeps walking) */
static void resume_suppress(void) { suppress_mask = (uint8_t)(raw_pad() & ACTION_BITS); }

/* Start and Select are both down and one of them has just been pressed */
static int chord_pressed(uint8_t pad) {
    int hit = (pad & CHORD_BITS) == CHORD_BITS && (pad & ~prev_game_pad & CHORD_BITS) != 0;
    prev_game_pad = pad;
    return hit;
}

/* before each real frame: keep the state it starts from and the pad it runs with */
static void chord_record(uint8_t pad) {
    if (!chord_states) return;
    nes_state_save(chord_states + (size_t)chord_head * chord_size, chord_size);
    chord_pads[chord_head] = pad;
    chord_pushed[chord_head] = 0;
    chord_head = (chord_head + 1) % CHORD_RING;
    if (chord_count < CHORD_RING) chord_count++;
}

/* a rewind record was pushed after the newest kept frame */
static void chord_mark_pushed(void) {
    if (chord_count > 0) chord_pushed[(chord_head + CHORD_RING - 1) % CHORD_RING] = 1;
}

/* the chord completed: undo the frames that ran with half of it held (scratch holds one
   state). Returns the number of frames undone. */
static int chord_rollback(void *scratch) {
    if (!chord_states) return 0;
    int k = 0, pushes = 0;
    while (k < chord_count) {
        int i = (chord_head + CHORD_RING - 1 - k) % CHORD_RING;
        if (!(chord_pads[i] & CHORD_BITS)) break;
        pushes += chord_pushed[i];
        k++;
    }
    if (k == 0 || k >= CHORD_RING) return 0;   /* nothing to undo, or held long before: a deliberate press */
    /* rewind records made on the undone frames go too (the first push after a clear makes no record) */
    if (pushes > rewind_count()) rewind_clear();
    else for (int i = 0; i < pushes; i++) rewind_pop(scratch);
    rewind_forget_redo();
    nes_state_load(chord_states + (size_t)((chord_head + CHORD_RING - k) % CHORD_RING) * chord_size, chord_size);
    allstars_reset();
    apu_flush_samples();
    chord_clear();
    return k;
}

/* ------------------------------------------------------------------ */
/* LT + RT: the menu on handhelds                                      */
/* ------------------------------------------------------------------ */
/* On Android and the Steam Deck, pulling both triggers together opens the menu, and in the menu
   closes it again. The triggers are no NES buttons, so the game has nothing to undo. What needs
   care is a hotkey on a trigger (fast-forward on RT by default): it acts only once its trigger has
   been held alone for TRIG_GRACE frames, so that pulling both never fast-forwards first, and after
   the chord the triggers act on nothing until both are released. */
#define TRIG_GRACE 6                 /* frames (100 ms) within which the second trigger counts as together */
static int trig_override = -1;       /* tests: the trigger bits to use instead of the controllers */
static int trig_now;                 /* triggers held: 1 LT, 2 RT */
static int trig_alone;               /* frames the one trigger now held has been held alone */
static int trig_latched;             /* the chord fired, or a binding was made: wait until both are released */

/* once per real frame: 1 when both triggers are down and one of them was just pulled */
static int trig_update(void) {
    if (!handheld) { trig_now = 0; return 0; }
    int t = trig_override >= 0 ? (trig_override & 3)
          : (input_held(SDLK_UNKNOWN, INPUT_PAD_LT) ? 1 : 0) | (input_held(SDLK_UNKNOWN, INPUT_PAD_RT) ? 2 : 0);
    int hit = t == 3 && trig_now != 3 && !trig_latched;
    if (t == 1 || t == 2) trig_alone = (t == trig_now) ? trig_alone + 1 : 1;
    else trig_alone = 0;
    trig_now = t;
    if (hit) trig_latched = 1;
    if (t == 0) trig_latched = 0;
    return hit;
}

/* a hotkey (rewind, fast-forward) held; on a trigger of the chord see above */
static int hotkey_held(int k) {
    int pad = cfg.pad[k];
    if (handheld && (pad == INPUT_PAD_LT || pad == INPUT_PAD_RT)) {
        if (input_held(cfg.key[k], -1)) return 1;    /* its keyboard key */
        int bit = pad == INPUT_PAD_LT ? 1 : 2;
        return !trig_latched && trig_now == bit && trig_alone >= TRIG_GRACE;
    }
    return input_held(cfg.key[k], pad);
}

/* ------------------------------------------------------------------ */
/* the Vs. cabinet's controls                                          */
/* ------------------------------------------------------------------ */
/* The cabinet has a coin slot, 1P and 2P start buttons and a stick with two buttons per player.
   The game reads the start buttons as the Select lines of the left and right controller, and a
   coin as a switch that must close and open again within a quarter of a second (held longer it
   counts as jammed and is refused). So Select (Insert coin) drops one coin per press, Start is the
   1P start button, 2P start has a binding of its own, and in a two-player game the stick and the
   buttons go to the controller of the player whose turn it is: one pad is passed between turns,
   as with the NES version. */
#define COIN_FRAMES 4                 /* frames one coin holds the slot switch closed */
static int coin_timer;                /* frames the current coin still holds it */
static int coin_was_down;             /* the coin button was down last frame: one coin per press */

static void vs_input(uint8_t pad) {
    int coin_down = (pad & 0x04) != 0;
    if (coin_down && !coin_was_down && coin_timer == 0) coin_timer = COIN_FRAMES;
    coin_was_down = coin_down;
    uint8_t coin = 0;
    if (coin_timer > 0) { coin = 1; coin_timer--; }
    uint8_t play = (uint8_t)(pad & 0xF3);                        /* A, B and the stick */
    /* SMB's NumberOfPlayers - 1 ($077A) and CurrentPlayer ($0753): Luigi's turn reads the right pad */
    int luigi = cart.vs && ram[0x077A] == 1 && ram[0x0753] == 1;
    uint8_t left = luigi ? 0 : play, right = luigi ? play : 0;
    if (pad & 0x08) left |= 0x04;                                /* 1P start */
    if (hotkey_held(K_START2)) right |= 0x04;                    /* 2P start */
    nes_set_pad(0, left);
    nes_set_pad(1, right);
    nes_set_vs_coin(coin);
}

/* ------------------------------------------------------------------ */
/* the rewind history after a rewind                                   */
/* ------------------------------------------------------------------ */
/* After a rewind the new frames are not recorded for REDO_WINDOW frames, as long as there is a
   rewound stretch: fast-forward pressed in that time still goes forward through it, to where the
   rewind began. The first record after that replaces the stretch. */
#define REDO_WINDOW 90               /* frames (1.5 s) */
static int redo_hold;

/* the game loop's history step after each emulated frame: a record every other frame.
   Returns 1 if a record was made. */
static int history_step(int frame, void *scratch, size_t size) {
    if (redo_hold > 0) redo_hold--;
    if ((frame & 1) || (redo_hold > 0 && rewind_redo_count() > 0)) return 0;
    nes_state_save(scratch, size);
    rewind_push(scratch);
    return 1;
}

