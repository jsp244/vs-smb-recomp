/* the DECK_EDITION build, or a Linux build that finds itself on a Steam Deck */
static int on_steam_deck(void) {
#if defined(DECK_EDITION)
    return 1;
#elif defined(__linux__) && !defined(__ANDROID__)
    const char *e = getenv("SteamDeck");
    if (e && e[0] == '1') return 1;
    char vendor[64] = "", product[64] = "";
    FILE *f = fopen("/sys/devices/virtual/dmi/id/board_vendor", "r");
    if (f) { if (!fgets(vendor, sizeof vendor, f)) vendor[0] = 0; fclose(f); }
    f = fopen("/sys/devices/virtual/dmi/id/product_name", "r");
    if (f) { if (!fgets(product, sizeof product, f)) product[0] = 0; fclose(f); }
    return strncmp(vendor, "Valve", 5) == 0 && (strncmp(product, "Jupiter", 7) == 0 || strncmp(product, "Galileo", 7) == 0);
#else
    return 0;
#endif
}

/* names of the files in dir with one of the extensions (3 letters, any case; the list ends with NULL), up to max */
static int list_files_ext(const char *dir, const char *const exts[], char names[][512], int max) {
    int n = 0;
#ifdef _WIN32
    for (int x = 0; exts[x] && n < max; x++) {
        wchar_t pattern[1300];
        char pat8[1300];
        snprintf(pat8, sizeof pat8, "%s\\*.%s", dir, exts[x]);
        if (!MultiByteToWideChar(CP_UTF8, 0, pat8, -1, pattern, 1300)) continue;
        WIN32_FIND_DATAW fd;
        HANDLE h = FindFirstFileW(pattern, &fd);
        if (h == INVALID_HANDLE_VALUE) continue;
        do {
            if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) &&
                WideCharToMultiByte(CP_UTF8, 0, fd.cFileName, -1, names[n], 512, NULL, NULL)) n++;
        } while (n < max && FindNextFileW(h, &fd));
        FindClose(h);
    }
#else
    DIR *d = opendir(dir);
    if (!d) return 0;
    struct dirent *e;
    while (n < max && (e = readdir(d)) != NULL) {
        size_t len = strlen(e->d_name);
        if (len <= 4 || len >= 512 || e->d_name[len - 4] != '.') continue;
        for (int x = 0; exts[x]; x++)
            if (SDL_strcasecmp(e->d_name + len - 3, exts[x]) == 0) { snprintf(names[n++], 512, "%s", e->d_name); break; }
    }
    closedir(d);
#endif
    return n;
}

/* names of the .nes and .zip files in dir (any case), up to max */
static int list_rom_files(const char *dir, char names[][512], int max) {
    static const char *const exts[] = { "nes", "zip", NULL };
    return list_files_ext(dir, exts, names, max);
}

